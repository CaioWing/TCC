#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path

import matplotlib.pyplot as plt


SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent

BACKEND_ORDER = ("eager", "sdpa", "triton")
BACKEND_LABELS = {
    "eager": "PyTorch eager",
    "sdpa": "PyTorch SDPA",
    "triton": "Triton custom",
}
BACKEND_COLORS = {
    "eager": "#4C566A",
    "sdpa": "#2E7D32",
    "triton": "#1565C0",
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--csv",
        type=Path,
        default=SCRIPT_DIR / "data" / "attention_benchmark_sweep.csv",
        help="Input CSV generated by benchmark_attention.py.",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=REPO_ROOT / "doc" / "figures",
        help="Directory where PDF figures will be written.",
    )
    parser.add_argument(
        "--roofline-csv",
        type=Path,
        default=SCRIPT_DIR / "data" / "attention_roofline_nsight.csv",
        help="Optional CSV generated by profile_attention_nsight.py.",
    )
    parser.add_argument(
        "--peak-tflops",
        type=float,
        help="Optional compute ceiling for the Roofline plot. Defaults to the maximum measured TFLOP/s.",
    )
    parser.add_argument(
        "--memory-bandwidth-gb-s",
        type=float,
        help="Optional memory bandwidth ceiling for the Roofline plot. Defaults to the maximum measured GB/s.",
    )
    parser.add_argument(
        "--style",
        choices=("auto", "bar", "line"),
        default="auto",
        help="Plot style. Auto uses line plots when there are more than four token counts.",
    )
    args = parser.parse_args()

    rows = read_rows(args.csv)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    style = resolve_style(args.style, rows)

    plot_metric(
        rows,
        metric="latency_ms",
        ylabel="Latencia media (ms)",
        title="Latencia da atencao densa",
        output_path=args.out_dir / "attention_latency.pdf",
        value_format="{:.4f}",
        style=style,
    )
    plot_metric(
        rows,
        metric="tflops",
        ylabel="Throughput efetivo (TFLOP/s)",
        title="Throughput efetivo da atencao densa",
        output_path=args.out_dir / "attention_throughput.pdf",
        value_format="{:.2f}",
        style=style,
    )
    plot_speedup(rows, args.out_dir / "attention_speedup.pdf", style=style)
    if args.roofline_csv.exists():
        roofline_rows = read_rows(args.roofline_csv)
        plot_roofline(
            roofline_rows,
            args.out_dir / "attention_roofline.pdf",
            peak_tflops=args.peak_tflops,
            memory_bandwidth_gb_s=args.memory_bandwidth_gb_s,
        )


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def seq_lens(rows: list[dict[str, str]]) -> list[int]:
    return sorted({int(row["seq_len"]) for row in rows})


def rows_by_seq_backend(rows: list[dict[str, str]]) -> dict[tuple[int, str], dict[str, str]]:
    return {(int(row["seq_len"]), row["backend"]): row for row in rows}


def resolve_style(style: str, rows: list[dict[str, str]]) -> str:
    if style != "auto":
        return style
    return "line" if len(seq_lens(rows)) > 4 else "bar"


def plot_metric(
    rows: list[dict[str, str]],
    *,
    metric: str,
    ylabel: str,
    title: str,
    output_path: Path,
    value_format: str,
    style: str,
) -> None:
    grouped_rows = rows_by_seq_backend(rows)
    sequences = seq_lens(rows)
    fig, ax = plt.subplots(figsize=(6.6, 3.8))
    if style == "line":
        for backend in BACKEND_ORDER:
            values = [float(grouped_rows[(seq_len, backend)][metric]) for seq_len in sequences]
            ax.plot(
                sequences,
                values,
                marker="o",
                markersize=3,
                linewidth=1.8,
                label=BACKEND_LABELS[backend],
                color=BACKEND_COLORS[backend],
            )
        ax.set_xticks(select_xticks(sequences))
    else:
        width = 0.23
        x_positions = list(range(len(sequences)))

        for backend_index, backend in enumerate(BACKEND_ORDER):
            offset = (backend_index - 1) * width
            values = [float(grouped_rows[(seq_len, backend)][metric]) for seq_len in sequences]
            bars = ax.bar(
                [x + offset for x in x_positions],
                values,
                width=width,
                label=BACKEND_LABELS[backend],
                color=BACKEND_COLORS[backend],
            )
            annotate_bars(ax, bars, value_format)
        ax.set_xticks(x_positions, [str(seq_len) for seq_len in sequences])

    ax.set_title(title)
    ax.set_xlabel("Numero de tokens (N)")
    ax.set_ylabel(ylabel)
    ax.grid(axis="y", alpha=0.25)
    ax.legend(frameon=False, ncols=3, loc="upper center", bbox_to_anchor=(0.5, 1.18))
    fig.tight_layout()
    fig.savefig(output_path, bbox_inches="tight")
    plt.close(fig)


def plot_speedup(rows: list[dict[str, str]], output_path: Path, *, style: str) -> None:
    grouped_rows = rows_by_seq_backend(rows)
    sequences = seq_lens(rows)
    fig, ax = plt.subplots(figsize=(6.6, 3.8))
    if style == "line":
        for backend in ("sdpa", "triton"):
            values = speedup_values(grouped_rows, sequences, backend)
            ax.plot(
                sequences,
                values,
                marker="o",
                markersize=3,
                linewidth=1.8,
                label=BACKEND_LABELS[backend],
                color=BACKEND_COLORS[backend],
            )
        ax.set_xticks(select_xticks(sequences))
    else:
        width = 0.28
        x_positions = list(range(len(sequences)))

        for backend_index, backend in enumerate(("sdpa", "triton")):
            offset = (backend_index - 0.5) * width
            values = speedup_values(grouped_rows, sequences, backend)
            bars = ax.bar(
                [x + offset for x in x_positions],
                values,
                width=width,
                label=BACKEND_LABELS[backend],
                color=BACKEND_COLORS[backend],
            )
            annotate_bars(ax, bars, "{:.2f}x")
        ax.set_xticks(x_positions, [str(seq_len) for seq_len in sequences])

    ax.axhline(1.0, color="#555555", linewidth=0.9, linestyle="--")
    ax.set_title("Speedup relativo ao PyTorch eager")
    ax.set_xlabel("Numero de tokens (N)")
    ax.set_ylabel("Speedup")
    ax.grid(axis="y", alpha=0.25)
    ax.legend(frameon=False, ncols=2, loc="upper center", bbox_to_anchor=(0.5, 1.18))
    fig.tight_layout()
    fig.savefig(output_path, bbox_inches="tight")
    plt.close(fig)


def plot_roofline(
    rows: list[dict[str, str]],
    output_path: Path,
    *,
    peak_tflops: float | None,
    memory_bandwidth_gb_s: float | None,
) -> None:
    points = [
        row
        for row in rows
        if valid_positive(row, "arithmetic_intensity_flop_per_byte")
        and valid_positive(row, "effective_tflops")
        and valid_positive(row, "dram_bandwidth_gb_s")
    ]
    if not points:
        return

    ai_values = [float(row["arithmetic_intensity_flop_per_byte"]) for row in points]
    tflops_values = [float(row["effective_tflops"]) for row in points]
    bandwidth_values = [float(row["dram_bandwidth_gb_s"]) for row in points]
    compute_ceiling = peak_tflops or max(tflops_values)
    bandwidth_ceiling = memory_bandwidth_gb_s or max(bandwidth_values)

    x_min = max(1.0, min(ai_values) / 1.4)
    x_max = max(ai_values) * 1.5
    x_roof = logspace(x_min, x_max, 180)
    memory_roof = [x * bandwidth_ceiling / 1000.0 for x in x_roof]
    compute_roof = [compute_ceiling for _ in x_roof]
    roofline = [min(memory_bound, compute_ceiling) for memory_bound in memory_roof]

    fig, ax = plt.subplots(figsize=(6.6, 4.2))
    ax.plot(x_roof, roofline, color="#111111", linewidth=1.6, label="Roofline empirico")
    ax.plot(x_roof, memory_roof, color="#777777", linewidth=1.0, linestyle="--", label="Limite de memoria")
    ax.plot(x_roof, compute_roof, color="#999999", linewidth=1.0, linestyle=":", label="Limite computacional")

    for backend in BACKEND_ORDER:
        backend_points = sorted(
            (row for row in points if row["backend"] == backend),
            key=lambda row: int(row["seq_len"]),
        )
        if not backend_points:
            continue
        x_values = [float(row["arithmetic_intensity_flop_per_byte"]) for row in backend_points]
        y_values = [float(row["effective_tflops"]) for row in backend_points]
        ax.plot(
            x_values,
            y_values,
            marker="o",
            markersize=4,
            linewidth=1.4,
            label=BACKEND_LABELS[backend],
            color=BACKEND_COLORS[backend],
        )
        last = backend_points[-1]
        ax.annotate(
            f"N={last['seq_len']}",
            (float(last["arithmetic_intensity_flop_per_byte"]), float(last["effective_tflops"])),
            textcoords="offset points",
            xytext=(5, 4),
            fontsize=7.5,
            color=BACKEND_COLORS[backend],
        )

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_title("Roofline empirico da atencao")
    ax.set_xlabel("Intensidade aritmetica (FLOP/byte DRAM)")
    ax.set_ylabel("Throughput efetivo (TFLOP/s)")
    ax.grid(True, which="both", alpha=0.22)
    ax.legend(frameon=False, fontsize=8, ncols=2, loc="upper left")
    ax.text(
        0.02,
        0.03,
        f"tetos: {compute_ceiling:.1f} TFLOP/s, {bandwidth_ceiling:.0f} GB/s",
        transform=ax.transAxes,
        fontsize=7.5,
        color="#555555",
    )
    fig.tight_layout()
    fig.savefig(output_path, bbox_inches="tight")
    plt.close(fig)


def speedup_values(
    grouped_rows: dict[tuple[int, str], dict[str, str]],
    sequences: list[int],
    backend: str,
) -> list[float]:
    values = []
    for seq_len in sequences:
        eager_latency = float(grouped_rows[(seq_len, "eager")]["latency_ms"])
        backend_latency = float(grouped_rows[(seq_len, backend)]["latency_ms"])
        values.append(eager_latency / backend_latency)
    return values


def valid_positive(row: dict[str, str], key: str) -> bool:
    try:
        value = float(row[key])
    except (KeyError, TypeError, ValueError):
        return False
    return math.isfinite(value) and value > 0.0


def logspace(start: float, stop: float, count: int) -> list[float]:
    log_start = math.log10(start)
    log_stop = math.log10(stop)
    step = (log_stop - log_start) / (count - 1)
    return [10 ** (log_start + index * step) for index in range(count)]


def select_xticks(sequences: list[int]) -> list[int]:
    if len(sequences) <= 12:
        return sequences
    step = max(1, len(sequences) // 8)
    ticks = sequences[::step]
    if ticks[-1] != sequences[-1]:
        ticks.append(sequences[-1])
    return ticks


def annotate_bars(ax: plt.Axes, bars, value_format: str) -> None:
    axis_top = ax.get_ylim()[1]
    for bar in bars:
        value = bar.get_height()
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            value + axis_top * 0.015,
            value_format.format(value),
            ha="center",
            va="bottom",
            fontsize=8,
        )
    ax.set_ylim(top=max(ax.get_ylim()[1], max(bar.get_height() for bar in bars) * 1.18))


if __name__ == "__main__":
    main()
